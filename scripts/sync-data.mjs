import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const content = Object.fromEntries(['industry','questions','milestones'].map(key => [key, JSON.parse(fs.readFileSync(path.join(root,'data',key+'.json'),'utf8'))]));
const generated = '// Generated by npm run sync from data/*.json. Edit the JSON sources, then regenerate.\nwindow.TACTILE_WORLD_DATA = '+JSON.stringify(content,null,2).replaceAll('<','\\u003c')+';\n';
const target = path.join(root,'web','knowledge.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== generated) throw new Error('Workbook data is stale. Run npm run sync.');
  console.log('Generated workbook data matches canonical JSON.');
} else {
  fs.writeFileSync(target,generated);
  console.log('Updated web/knowledge.js from canonical JSON.');
}

